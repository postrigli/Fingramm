package app.fingramm.security

import javax.inject.Inject
import javax.inject.Singleton

/**
 * Отмечает, что приложение само открыло системное окно, из которого вернётся с результатом (выбор файла для
 * экспорта и импорта). Такое окно уводит приложение в фон; без отметки оно заблокировалось бы, интерфейс был бы
 * разрушен и результат выбора пропал.
 *
 * Отметка действует на один уход в фон и сбрасывается при получении результата. Пока системное окно открыто,
 * вернуться в приложение, минуя его, нельзя: окно остаётся верхним в задаче, поэтому лазейки для обхода блокировки нет.
 */
@Singleton
class ExternalFlowGuard @Inject constructor() {
    @Volatile
    private var active = false

    /** Вызывается перед запуском системного окна. */
    fun begin() {
        active = true
    }

    /** Вызывается, когда результат получен (в том числе отмена) или окно не удалось открыть. */
    fun end() {
        active = false
    }

    /** Приложение ушло в фон: возвращает true, если это ожидаемый уход (и снимает отметку). */
    fun consume(): Boolean {
        val wasActive = active
        active = false
        return wasActive
    }
}
